# Generate src/Boot/PluginVersion.g.cs from manifest.json (single source of truth)
# Called by the GeneratePluginVersion MSBuild target before every build.
param([string]$Manifest, [string]$Output)

$ErrorActionPreference = "Stop"

# Read with explicit UTF8 so BOM-less files are handled the same everywhere
$raw = [System.IO.File]::ReadAllText($Manifest, [System.Text.Encoding]::UTF8)
$j = $raw | ConvertFrom-Json
$version = [string]$j.version_number
if ([string]::IsNullOrWhiteSpace($version)) {
    throw "manifest.json has no version_number field"
}

$nl = [System.Environment]::NewLine
$q = [char]34
$sb = New-Object System.Text.StringBuilder
[void]$sb.Append('namespace PeakCSR')
[void]$sb.Append($nl)
[void]$sb.Append('{')
[void]$sb.Append($nl)
[void]$sb.Append('    // Auto-generated by MSBuild from manifest.json. Do not edit by hand.')
[void]$sb.Append($nl)
[void]$sb.Append('    public static class PluginVersionConstant')
[void]$sb.Append($nl)
[void]$sb.Append('    {')
[void]$sb.Append($nl)
[void]$sb.Append('        public const string Version = ' + $q + $version + $q + ';')
[void]$sb.Append($nl)
[void]$sb.Append('    }')
[void]$sb.Append($nl)
[void]$sb.Append('}')
[void]$sb.Append($nl)

$utf8NoBom = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllText($Output, $sb.ToString(), $utf8NoBom)
Write-Host '[PeakCSR] PluginVersion.g.cs generated (version ' $version ')' -ForegroundColor DarkGray
